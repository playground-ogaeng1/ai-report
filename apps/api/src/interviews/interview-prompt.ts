/**
 * 대화 맨 앞에 항상 붙이는 사용자 턴.
 *
 * Messages API 는 **첫 메시지가 user** 여야 합니다. 그런데 면접은 면접관이
 * 먼저 질문하므로 저장된 첫 메시지는 assistant 입니다. 그대로 보내면
 * 400 이 나므로, 매 요청마다 이 한 줄을 맨 앞에 끼워 넣습니다.
 * (DB 에는 저장하지 않습니다 — 화면에 보일 내용이 아닙니다)
 *
 * 값이 고정이라 프롬프트 캐시도 깨지지 않습니다.
 *
 * ⚠️ **"면접을 시작해 주세요." 만 보내면 안 됩니다.** 그건 "모의 면접을 하나
 * 만들어 달라"는 의뢰로도 읽히고, 시스템 프롬프트에 지원자의 문서 전문이
 * 들어 있어서 모델이 지원자 답변까지 지어내 **대화록 전체를 한 번에**
 * 써 버립니다. 그래서 "질문 하나만 하고 내 답을 기다려라" 를 함께 싣고,
 * 화자를 지원자("제 답변")로 못 박아 턴 주고받기임을 분명히 합니다.
 */
export const KICKOFF_MESSAGE =
  '면접을 시작해 주세요. 첫 질문 하나만 하고, 제 답변을 기다려 주세요.';

/**
 * 면접관 발언을 감싸는 태그.
 *
 * 왜 태그가 필요한가: 모델이 지원자 답변까지 혼자 써 내려가는 걸 막아야
 * 하는데, **화자 표시 없이 평문으로** 이어 쓰기 때문에 `지원자:` 같은
 * 정지 문자열로는 잡히지 않습니다. 실제로 이렇게 나왔습니다:
 *
 *   …어떤 기준으로 산정하신 겁니까?      ← 면접관
 *   커밋 수를 기준으로 산정했습니다.      ← 모델이 지어낸 지원자 답변
 *   프론트엔드 개발자가 두 명인데…         ← 면접관 꼬리질문
 *
 * 그래서 출력에 **경계를 만들고** 닫는 태그를 `stop_sequences` 로 씁니다.
 * 프롬프트는 확률이지만 정지 문자열은 확정입니다 — 모델이 턴을 끝내는
 * 순간 생성 자체가 멈추므로 뒤를 이어 쓸 방법이 없습니다.
 */
export const QUESTION_OPEN = '<질문>';
export const QUESTION_CLOSE = '</질문>';

/**
 * 스트리밍 중 누적된 원문에서 **사용자에게 보여줄 부분**만 꺼냅니다.
 *
 * 델타가 `'<질'`, `'문>'` 처럼 쪼개져 오기 때문에 조각 하나만 보고 판단할
 * 수 없습니다. 여는 태그가 완성될 때까지는 **보류**합니다(빈 문자열 반환).
 *
 * 모델이 태그를 아예 안 쓴 경우에는 원문을 그대로 보여줍니다 — 태그는
 * 안전장치이고, 없다고 해서 질문을 날려 버리면 더 나쁩니다.
 */
export function visibleQuestionText(raw: string): string {
  const text = raw.trimStart();

  // 아직 여는 태그의 일부만 도착했습니다 (''도 여기 걸립니다).
  if (QUESTION_OPEN.startsWith(text)) return '';

  const body = text.startsWith(QUESTION_OPEN)
    ? text.slice(QUESTION_OPEN.length)
    : text;

  // 닫는 태그는 stop_sequences 가 떼어 주지만, 사고 토큰이 한도를 먹어
  // 중간에 끊기면 `'</질문'` 처럼 조각이 남을 수 있습니다.
  for (let i = QUESTION_CLOSE.length; i > 0; i -= 1) {
    const tail = QUESTION_CLOSE.slice(0, i);
    if (body.endsWith(tail)) return body.slice(0, -i);
  }
  return body;
}

/**
 * 첫 질문의 **시작 각도** 후보.
 *
 * 왜 필요한가: Claude Opus 5 는 `temperature` 를 받지 않습니다(보내면 400).
 * 같은 문서·난이도면 입력이 바이트 단위로 같아서 첫 질문이 거의 똑같이
 * 나옵니다. 그래서 변화를 **프롬프트 쪽에서** 만들어야 합니다.
 *
 * 난수 문자열을 섞는 대신 각도를 고르는 이유: 표현만 흔들리는 게 아니라
 * 질문의 방향이 실제로 달라져야 연습 가치가 있습니다.
 *
 * 첫 턴에만 붙입니다. 생성된 첫 질문은 DB 에 저장되므로 이후 턴은 저장된
 * 대화를 따라가면 되고, 각도 지시문을 계속 들고 있을 필요가 없습니다.
 */
